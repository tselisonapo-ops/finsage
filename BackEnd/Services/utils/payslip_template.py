def render_payslip_pdf(
    company_id: int,
    payroll_run_id: int,
    employee_id: int,
    logo_path: str | None = None,
) -> bytes:
    """
    Build a payslip PDF for the given employee in the given payroll run.

    Args:
        logo_path: Optional local file path to override the logo image.
            If None, falls back to ``company.logo_url`` and then the
            bundled system logo (``assets/finsage_logo.png``).

    Returns the PDF as ``bytes``.
    """
    payload = db_service.payroll_payslip_get(
        company_id,
        payroll_run_id,
        employee_id,
    )

    if not payload:
        raise ValueError(
            "Payslip payload not available. Ensure payroll has been calculated."
        )

    return _build_pdf(payload, logo_path=logo_path)


def save_payslip_pdf(
    company_id: int,
    payroll_run_id: int,
    employee_id: int,
    output_path: str,
    logo_path: str | None = None,
) -> str:
    """
    Render the payslip PDF and write it to ``output_path``.
    Returns the path written to.
    """
    pdf_bytes = render_payslip_pdf(
        company_id, payroll_run_id, employee_id, logo_path=logo_path
    )
    with open(output_path, "wb") as fh:
        fh.write(pdf_bytes)
    return output_path


def render_payslip_pdf_from_payload(
    payload: dict,
    logo_path: str | None = None,
) -> bytes:
    """
    Build a payslip PDF from an already-loaded payload dict.
    Useful for preview / testing without hitting the DB.
    """
    return _build_pdf(payload, logo_path=logo_path)


