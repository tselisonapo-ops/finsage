def _header_block(
    payload: dict,
    styles: dict,
    logo_path_override: str | None = None,
) -> Table:
    """
    Top banner. Layout (left → right):

        +----------+-------------------+---------------------------+
        | [LOGO]   | SYSTEM NAME       |  COMPANY NAME             |
        |          | tagline           |  reg / tin / vat          |
        |          |                   |  address / phone / email  |
        +----------+-------------------+---------------------------+
        |                     PAYSLIP                              |
        |  Run No | Period | Pay Date | Currency | Status           |
        +----------------------------------------------------------+
    """
    company = payload.get("company", {}) or {}
    run = payload.get("run", {}) or {}

    # ---- Logo cell ----------------------------------------------------
    logo_img = _load_logo(company, logo_path_override=logo_path_override)
    if logo_img is not None:
        logo_cell = logo_img
    else:
        # Fallback: a navy square with the system initial (white text)
        # Drawn as a 1-cell Table with a colored background.
        initial = (SYSTEM_NAME or "F")[:1].upper()
        initial_tbl = Table(
            [[Paragraph(f'<font color="white" size="14"><b>{initial}</b></font>',
                         styles["cell"])]],
            colWidths=[20 * mm],
            rowHeights=[20 * mm],
        )
        initial_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), BRAND_PRIMARY),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("BOX", (0, 0), (-1, -1), 0.5, BRAND_PRIMARY),
        ]))
        logo_cell = initial_tbl

    # ---- System banner cell (name + tagline) ------------------------
    system_lines = [
        Paragraph(SYSTEM_NAME, styles["system_name"]),
        Paragraph(SYSTEM_TAGLINE, styles["system_tagline"]),
    ]
    system_banner = Table(
        [[system_lines[0]], [system_lines[1]]],
        colWidths=[55 * mm],
        rowHeights=[14, 10],
    )
    system_banner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), BRAND_PRIMARY),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 1),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
    ]))

    # ---- Company details cell ----------------------------------------
    # Pulls all field-name variants returned by db_service.payroll_payslip_get
    # AND the /api/companies/<id> endpoint (company_reg_no, tin, vat,
    # company_email, company_phone, physical_address, postal_address, etc.)
    company_lines = []
    name = _coalesce(
        company.get("name"),
        company.get("company_name"),
        "Company",
    )
    company_lines.append(Paragraph(name, styles["company_name"]))

    meta_bits = []
    reg = _coalesce(
        company.get("registration_number"),
        company.get("company_reg_no"),
    )
    if reg:
        meta_bits.append(f"Reg: {reg}")
    tin = _coalesce(
        company.get("tax_number"),
        company.get("tin"),
    )
    if tin:
        meta_bits.append(f"TIN: {tin}")
    vat = _coalesce(
        company.get("vat_number"),
        company.get("vat"),
    )
    if vat:
        meta_bits.append(f"VAT: {vat}")
    if meta_bits:
        company_lines.append(
            Paragraph(" &nbsp;|&nbsp; ".join(meta_bits), styles["company_meta"])
        )

    addr = _coalesce(
        company.get("address"),
        company.get("billing_address"),
        company.get("physical_address"),
        company.get("postal_address"),
    )
    if addr:
        company_lines.append(Paragraph(addr, styles["company_meta"]))

    contact_bits = []
    phone = _coalesce(
        company.get("phone"),
        company.get("company_phone"),
    )
    if phone:
        contact_bits.append(f"Tel: {phone}")
    email = _coalesce(
        company.get("email"),
        company.get("company_email"),
    )
    if email:
        contact_bits.append(f"Email: {email}")
    if contact_bits:
        company_lines.append(
            Paragraph(" &nbsp;|&nbsp; ".join(contact_bits), styles["company_meta"])
        )

    company_cell = []
    for p in company_lines:
        company_cell.append(p)

    # ---- Run info cell (right side) ----------------------------------
    run_no = _safe_str(run.get("run_no") or run.get("id"))
    period = f"{_safe_date(run.get('period_start'))} - {_safe_date(run.get('period_end'))}"
    pay_date = _safe_date(run.get("payment_date"))
    currency = run.get("currency") or "LSL"
    status = _safe_str(run.get("status")).upper()

    right_block = [
        [Paragraph("PAYSLIP", styles["doc_title"])],
        [Paragraph(f"Run No: <b>{run_no}</b> &nbsp;|&nbsp; Period: <b>{period}</b>",
                   styles["doc_subtitle"])],
        [Paragraph(
            f"Pay Date: <b>{pay_date}</b> &nbsp;|&nbsp; "
            f"Currency: <b>{currency}</b> &nbsp;|&nbsp; Status: <b>{status}</b>",
            styles["doc_subtitle"],
        )],
    ]
    right_table = Table(right_block, colWidths=[CONTENT_WIDTH * 0.40])
    right_table.setStyle(TableStyle([
        ("ALIGN", (0, 0), (-1, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))

    # ---- Assemble header row -----------------------------------------
    # Widths: logo (20mm) + system banner (55mm) + company (~remaining) + run info
    # Total = CONTENT_WIDTH
    logo_w = 22 * mm
    banner_w = 55 * mm
    right_w = CONTENT_WIDTH * 0.40
    company_w = CONTENT_WIDTH - logo_w - banner_w - right_w

    data = [[logo_cell, system_banner, company_cell, right_table]]
    tbl = Table(
        data,
        colWidths=[logo_w, banner_w, company_w, right_w],
    )
    tbl.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ALIGN", (0, 0), (0, 0), "CENTER"),
        ("ALIGN", (1, 0), (1, 0), "LEFT"),
        ("ALIGN", (2, 0), (2, 0), "LEFT"),
        ("ALIGN", (3, 0), (3, 0), "RIGHT"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("LINEBELOW", (0, 0), (-1, -1), 1.2, BRAND_PRIMARY),
    ]))
    return tbl


def _kv_table(rows: list, col_widths: list, styles: dict) -> Table:
    """rows = [[Paragraph(label), Paragraph(value)], ...]"""
    data = []
    for row in rows:
        data.append(row)
    tbl = Table(data, colWidths=col_widths)
    tbl.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 1),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]))
    return tbl


def _employee_block(payload: dict, styles: dict) -> Table:
    emp = payload.get("employee", {}) or {}
    bank = emp.get("bank", {}) or {}

    currency = (payload.get("run", {}) or {}).get("currency") or "LSL"

    name = emp.get("employee_name") or " ".join(
        filter(None, [emp.get("first_name"), emp.get("last_name")])
    )

    def cell(label, value):
        return [
            Paragraph(label, styles["label"]),
            Paragraph(_safe_str(value) or "-", styles["value"]),
        ]

    # 12 fields → 4 columns × 3 rows (label/value pairs side by side)
    pairs = [
        cell("Employee No.", emp.get("employee_no")),
        cell("Full Name", name),
        cell("ID / Passport", emp.get("id_number") or emp.get("passport_number")),
        cell("Tax Number", emp.get("tax_number")),
        cell("Department", emp.get("department_name")),
        cell("Position", emp.get("position_title")),
        cell("Bank", bank.get("bank_name")),
        cell("Branch Code", bank.get("branch_code")),
        cell("Account No.", bank.get("account_number")),
        cell("Account Type", bank.get("account_type")),
        cell("Account Holder", bank.get("account_holder_name")),
        cell("Pay Currency", currency),
    ]

    # Layout: 4 columns, each column is (label, value) stacked.
    # Build rows: row 0 = labels, row 1 = values, row 2 = labels, row 3 = values...
    # Easier: 3 data rows, each row contains 4 cells, each cell is a mini-table[label,value]
    col_w = CONTENT_WIDTH / 4
    rows = []
    for i in range(0, len(pairs), 4):
        row_cells = []
        for j in range(4):
            if i + j < len(pairs):
                lbl, val = pairs[i + j]
                mini = Table([[lbl], [val]], colWidths=[col_w - 8])
                mini.setStyle(TableStyle([
                    ("TOPPADDING", (0, 0), (-1, -1), 0),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
                    ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ]))
                row_cells.append(mini)
            else:
                row_cells.append("")
        rows.append(row_cells)

    data = [
        [Paragraph("EMPLOYEE &amp; PAYMENT DETAILS", styles["section_header"]), "", "", ""]
    ] + rows

    tbl = Table(data, colWidths=[col_w] * 4)
    tbl.setStyle(TableStyle([
        ("SPAN", (0, 0), (-1, 0)),
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_HEADER_BG),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, 0), 3),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 3),
        ("LEFTPADDING", (0, 0), (-1, 0), 6),
        ("TOPPADDING", (0, 1), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 3),
        ("LEFTPADDING", (0, 1), (-1, -1), 6),
        ("RIGHTPADDING", (0, 1), (-1, -1), 6),
        ("BOX", (0, 0), (-1, -1), 0.6, BRAND_BORDER),
        ("BACKGROUND", (0, 1), (-1, -1), BRAND_SOFT),
    ]))
    return tbl


