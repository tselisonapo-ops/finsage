# ---------------------------------------------------------------------------
# Page decoration (footer drawn on canvas)
# ---------------------------------------------------------------------------
def _on_page(canvas, doc):
    canvas.saveState()
    # bottom rule
    canvas.setStrokeColor(BRAND_BORDER)
    canvas.setLineWidth(0.4)
    canvas.line(LEFT_MARGIN, BOTTOM_MARGIN - 4, PAGE_W - RIGHT_MARGIN, BOTTOM_MARGIN - 4)
    # footer text
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(BRAND_MUTED)
    generated = datetime.now().strftime("%d %b %Y %H:%M")
    footer_left = f"Generated by {SYSTEM_NAME}  |  {generated}"
    footer_right = (
        f"Page {doc.page}  |  "
        f"This is a system-generated payslip and is valid without signature."
    )
    canvas.drawString(LEFT_MARGIN, BOTTOM_MARGIN - 12, footer_left)
    canvas.drawRightString(PAGE_W - RIGHT_MARGIN, BOTTOM_MARGIN - 12, footer_right)
    canvas.restoreState()


