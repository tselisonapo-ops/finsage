def _build_pdf(payload: dict, logo_path: str | None = None) -> bytes:
    styles = _build_styles()
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=LEFT_MARGIN,
        rightMargin=RIGHT_MARGIN,
        topMargin=TOP_MARGIN,
        bottomMargin=BOTTOM_MARGIN,
        title=f"Payslip - {SYSTEM_NAME}",
        author=SYSTEM_NAME,
    )

    story = []

    # Header (logo + system name + company + run info)
    story.append(_header_block(payload, styles, logo_path_override=logo_path))
    story.append(Spacer(1, 4))

    # Employee + bank details
    story.append(_employee_block(payload, styles))
    story.append(Spacer(1, 4))

    # Eligibility & proration
    story.append(_eligibility_block(payload, styles))
    story.append(Spacer(1, 6))

    # Earnings + Deductions side-by-side
    story.append(_earnings_deductions_block(payload, styles))
    story.append(Spacer(1, 6))

    # Taxes + Employer contributions side-by-side
    story.append(_taxes_contrib_block(payload, styles))
    story.append(Spacer(1, 6))

    # Totals summary
    story.append(_totals_block(payload, styles))
    story.append(Spacer(1, 4))

    # Net pay banner
    story.append(_net_pay_block(payload, styles))
    story.append(Spacer(1, 4))

    # Tax + calculation footnote
    story.append(_tax_footer_block(payload, styles))

    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)
    return buffer.getvalue()
