def _money(value, currency: str = "LSL") -> str:
    """Format a Decimal/float/None as a currency string."""
    if value is None:
        amount_str = "0.00"
    elif isinstance(value, Decimal):
        amount_str = f"{value:,.2f}"
    elif isinstance(value, (int, float)):
        amount_str = f"{Decimal(str(value)):,.2f}"
    else:
        try:
            amount_str = f"{Decimal(str(value)):,.2f}"
        except Exception:
            amount_str = "0.00"
    return f"{currency} {amount_str}"


def _safe_str(value) -> str:
    if value is None:
        return ""
    return str(value)


def _safe_date(value) -> str:
    if not value:
        return "-"
    if isinstance(value, datetime):
        return value.strftime("%d %b %Y")
    try:
        return datetime.strptime(str(value)[:10], "%Y-%m-%d").strftime("%d %b %Y")
    except Exception:
        return str(value)


def _decimal(value) -> Decimal:
    if value is None:
        return Decimal("0")
    if isinstance(value, Decimal):
        return value
    try:
        return Decimal(str(value))
    except Exception:
        return Decimal("0")


def _load_logo(
    company: dict,
    logo_path_override: str | None = None,
    width: float = 20 * mm,
    height: float = 20 * mm,
):
    """
    Return a ReportLab Image flowable for the company logo, or None.

    Resolution order:
        1. logo_path_override argument (caller-supplied file path)
        2. company['logo_url'] (URL or local file path from DB)
        3. DEFAULT_LOGO_PATH (bundled Finsage asset)

    If none of the above resolve to a readable image, returns None and the
    caller falls back to drawing a colored square with the system initial.
    """
    candidates = []
    if logo_path_override:
        candidates.append(logo_path_override)
    if company.get("logo_url"):
        candidates.append(company["logo_url"])
    candidates.append(DEFAULT_LOGO_PATH)

    for path in candidates:
        if not path:
            continue
        # URLs are not supported by ReportLab directly — only local files.
        if path.startswith(("http://", "https://")):
            continue
        if not os.path.isfile(path):
            continue
        try:
            return Image(path, width=width, height=height)
        except Exception:
            continue
    return None


def _coalesce(*values):
    """Return the first non-None, non-empty value; else None."""
    for v in values:
        if v is None:
            continue
        if isinstance(v, str) and not v.strip():
            continue
        return v
    return None


